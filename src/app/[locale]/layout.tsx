import { NextIntlClientProvider } from 'next-intl';
import { hasLocale } from 'next-intl';
import { notFound } from 'next/navigation';
import { Baloo_2, Nunito } from 'next/font/google';
import type { Metadata } from 'next';
import '@/css/styles.css';
import Header from '@components/header/Header';
import Footer from '@components/footer/Footer';
import { routing } from '@/i18n/routing';
import { Toast } from '@heroui/react';
import TanstackProvider from '@shared/providers/TanstackProvider';

export const metadata: Metadata = {
    title: 'FindPaw',
    description: 'Generated by Pet app',
};

const nunito = Nunito({
    subsets: ['latin', 'cyrillic'],
    variable: '--font-nunito',
});

// Display titles only. No Cyrillic in Baloo 2; the site ships en/cs (latin-ext).
const baloo = Baloo_2({
    subsets: ['latin', 'latin-ext'],
    variable: '--font-baloo',
});

export default async function RootLayout({
    children,
    params,
}: Readonly<{
    children: React.ReactNode;
    params: Promise<{ locale: string }>;
}>) {
    const { locale } = await params;

    if (!hasLocale(routing.locales, locale)) {
        notFound();
    }
    return (
        <html lang={locale} className={`${nunito.variable} ${baloo.variable}`}>
            <body className="bg-background text-foreground">
                <TanstackProvider>
                    <NextIntlClientProvider locale={locale}>
                        <Toast.Provider />
                        {/* Header and page fill the screen; the footer
                            always starts below the fold. */}
                        <div className="flex flex-col min-h-dvh">
                            <Header />
                            {children}
                        </div>
                        <Footer />
                    </NextIntlClientProvider>
                </TanstackProvider>
            </body>
        </html>
    );
}
